const PACKAGE_SUFFIXES: [(&str, &str); 10] = [
    ("Windows", "windows-x64-v3-setup.exe"),
    ("Windows", "windows-x64-setup.exe"),
    ("Windows", "windows-arm64-setup.exe"),
    ("Linux", "linux-x64.AppImage"),
    ("Linux", "linux-arm64.AppImage"),
    ("macOS", "macos-arm64.dmg"),
    ("macOS", "macos-x64.dmg"),
    ("Android", "android-arm64-v8a.apk"),
    ("Android", "android-armeabi-v7a.apk"),
    ("Android", "android-x86_64.apk"),
];

const fn package(i: usize, label: &'static str, note: &'static str) -> Package {
    Package {
        platform: PACKAGE_SUFFIXES[i].0,
        suffix: PACKAGE_SUFFIXES[i].1,
        label,
        note,
    }
}

